
-- ============================================================
-- 006: Form & Page Identity Registry
-- Cloudflare D1 / SQLite
--
-- Includes:
--   1. Form registry
--   2. Page registry
--   3. Application-bound page references
--   4. Shared form locations
--   5. Activity audit ledger
--   6. Integrity checks, indexes and consistency triggers
--
-- IMPORTANT:
-- IDs and page references must be generated server-side.
-- This migration does not generate QR images or authorize users.
-- ============================================================

PRAGMA foreign_keys = ON;

-- ============================================================
-- 1. FORM REGISTRY
-- ============================================================

CREATE TABLE IF NOT EXISTS form_registry (
    form_id TEXT PRIMARY KEY
        CHECK (length(form_id) BETWEEN 8 AND 128),

    form_code TEXT NOT NULL UNIQUE
        CHECK (length(form_code) BETWEEN 3 AND 100),

    form_name TEXT NOT NULL
        CHECK (length(trim(form_name)) BETWEEN 1 AND 200),

    form_version INTEGER NOT NULL DEFAULT 1
        CHECK (form_version >= 1),

    route_path TEXT NOT NULL UNIQUE
        CHECK (
            length(route_path) BETWEEN 1 AND 500
            AND substr(route_path, 1, 1) = '/'
            AND instr(route_path, '?') = 0
            AND instr(route_path, '#') = 0
        ),

    form_status TEXT NOT NULL DEFAULT 'active'
        CHECK (form_status IN ('active', 'locked', 'archived')),

    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_form_registry_status
    ON form_registry(form_status);

CREATE INDEX IF NOT EXISTS idx_form_registry_created
    ON form_registry(created_at);


-- ============================================================
-- 2. FORM PAGE REGISTRY
-- Every registered page belongs to exactly one form.
-- ============================================================

CREATE TABLE IF NOT EXISTS form_page_registry (
    page_id TEXT PRIMARY KEY
        CHECK (length(page_id) BETWEEN 8 AND 128),

    form_id TEXT NOT NULL,

    page_code TEXT NOT NULL UNIQUE
        CHECK (length(page_code) BETWEEN 3 AND 100),

    page_name TEXT NOT NULL
        CHECK (length(trim(page_name)) BETWEEN 1 AND 200),

    page_number INTEGER NOT NULL
        CHECK (page_number >= 1),

    route_path TEXT NOT NULL UNIQUE
        CHECK (
            length(route_path) BETWEEN 1 AND 500
            AND substr(route_path, 1, 1) = '/'
            AND instr(route_path, '?') = 0
            AND instr(route_path, '#') = 0
        ),

    page_version INTEGER NOT NULL DEFAULT 1
        CHECK (page_version >= 1),

    page_status TEXT NOT NULL DEFAULT 'active'
        CHECK (page_status IN ('active', 'locked', 'archived')),

    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (form_id)
        REFERENCES form_registry(form_id)
        ON DELETE RESTRICT,

    UNIQUE (form_id, page_number),
    UNIQUE (form_id, page_name),

    -- Supports a composite FK that checks the page's parent form.
    UNIQUE (form_id, page_id)
);

CREATE INDEX IF NOT EXISTS idx_form_pages_form
    ON form_page_registry(form_id);

CREATE INDEX IF NOT EXISTS idx_form_pages_status
    ON form_page_registry(page_status);

CREATE INDEX IF NOT EXISTS idx_form_pages_created
    ON form_page_registry(created_at);


-- ============================================================
-- 3. APPLICATION PAGE INSTANCES
-- Each reference belongs to an application and registered page.
-- Tokens must be unpredictable and generated by the backend.
-- ============================================================

CREATE TABLE IF NOT EXISTS application_page_instances (
    page_instance_id TEXT PRIMARY KEY
        CHECK (length(page_instance_id) BETWEEN 8 AND 128),

    application_ref TEXT NOT NULL
        CHECK (length(application_ref) BETWEEN 1 AND 160),

    form_id TEXT NOT NULL,

    page_id TEXT NOT NULL,

    page_ref TEXT NOT NULL UNIQUE
        CHECK (length(page_ref) BETWEEN 24 AND 512),

    reference_version INTEGER NOT NULL DEFAULT 1
        CHECK (reference_version >= 1),

    page_version INTEGER NOT NULL
        CHECK (page_version >= 1),

    verification_status TEXT NOT NULL DEFAULT 'issued'
        CHECK (
            verification_status IN (
                'issued', 'verified', 'revoked', 'expired'
            )
        ),

    issued_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,

    expires_at TEXT,

    last_verified_at TEXT,

    FOREIGN KEY (form_id, page_id)
        REFERENCES form_page_registry(form_id, page_id)
        ON DELETE RESTRICT,

    UNIQUE (application_ref, page_id, reference_version)
);

CREATE INDEX IF NOT EXISTS idx_page_instances_application
    ON application_page_instances(application_ref);

CREATE INDEX IF NOT EXISTS idx_page_instances_form_page
    ON application_page_instances(form_id, page_id);

CREATE INDEX IF NOT EXISTS idx_page_instances_status
    ON application_page_instances(verification_status);

CREATE INDEX IF NOT EXISTS idx_page_instances_expiry
    ON application_page_instances(expires_at);


-- ============================================================
-- 4. SHARED FORM LOCATIONS
-- Records where forms and pages are published or embedded.
-- ============================================================

CREATE TABLE IF NOT EXISTS shared_form_locations (
    location_id TEXT PRIMARY KEY
        CHECK (length(location_id) BETWEEN 8 AND 128),

    form_id TEXT NOT NULL,

    page_id TEXT,

    location_name TEXT NOT NULL
        CHECK (length(trim(location_name)) BETWEEN 1 AND 200),

    location_type TEXT NOT NULL
        CHECK (
            location_type IN (
                'website', 'admin', 'shared_link', 'embed', 'other'
            )
        ),

    route_path TEXT
        CHECK (
            route_path IS NULL
            OR (
                length(route_path) BETWEEN 1 AND 500
                AND substr(route_path, 1, 1) = '/'
                AND instr(route_path, '?') = 0
                AND instr(route_path, '#') = 0
            )
        ),

    location_status TEXT NOT NULL DEFAULT 'active'
        CHECK (location_status IN ('active', 'disabled', 'archived')),

    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (form_id)
        REFERENCES form_registry(form_id)
        ON DELETE RESTRICT,

    -- If page_id is supplied, ensure it belongs to form_id.
    FOREIGN KEY (form_id, page_id)
        REFERENCES form_page_registry(form_id, page_id)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_locations_form
    ON shared_form_locations(form_id);

CREATE INDEX IF NOT EXISTS idx_locations_page
    ON shared_form_locations(page_id);

CREATE INDEX IF NOT EXISTS idx_locations_status
    ON shared_form_locations(location_status);


-- ============================================================
-- 5. ACTIVITY AUDIT LEDGER
-- Record outcomes without storing secrets or uploaded documents.
-- ============================================================

CREATE TABLE IF NOT EXISTS activity_events (
    event_id TEXT PRIMARY KEY
        CHECK (length(event_id) BETWEEN 8 AND 128),

    event_code TEXT NOT NULL UNIQUE
        CHECK (length(event_code) BETWEEN 3 AND 120),

    actor_id TEXT,

    actor_role TEXT NOT NULL DEFAULT 'system'
        CHECK (
            actor_role IN (
                'system', 'applicant', 'admin', 'owner', 'service'
            )
        ),

    action TEXT NOT NULL
        CHECK (length(trim(action)) BETWEEN 1 AND 120),

    form_id TEXT,

    page_id TEXT,

    application_ref TEXT,

    page_ref TEXT,

    location_id TEXT,

    request_id TEXT,

    outcome TEXT NOT NULL DEFAULT 'success'
        CHECK (outcome IN ('success', 'denied', 'failed', 'blocked')),

    details_json TEXT
        CHECK (
            details_json IS NULL
            OR (
                json_valid(details_json)
                AND length(details_json) <= 12000
            )
        ),

    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (form_id)
        REFERENCES form_registry(form_id)
        ON DELETE RESTRICT,

    FOREIGN KEY (page_id)
        REFERENCES form_page_registry(page_id)
        ON DELETE RESTRICT,

    FOREIGN KEY (location_id)
        REFERENCES shared_form_locations(location_id)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_activity_created
    ON activity_events(created_at);

CREATE INDEX IF NOT EXISTS idx_activity_application
    ON activity_events(application_ref);

CREATE INDEX IF NOT EXISTS idx_activity_form_page
    ON activity_events(form_id, page_id);

CREATE INDEX IF NOT EXISTS idx_activity_action
    ON activity_events(action);

CREATE INDEX IF NOT EXISTS idx_activity_outcome
    ON activity_events(outcome);

CREATE INDEX IF NOT EXISTS idx_activity_request
    ON activity_events(request_id);


-- ============================================================
-- 6. CONSISTENCY TRIGGERS
-- Prevent mismatched form/page combinations in activity records.
-- ============================================================

CREATE TRIGGER IF NOT EXISTS trg_activity_validate_form_page_insert
BEFORE INSERT ON activity_events
WHEN NEW.form_id IS NOT NULL
 AND NEW.page_id IS NOT NULL
 AND NOT EXISTS (
    SELECT 1
    FROM form_page_registry p
    WHERE p.form_id = NEW.form_id
      AND p.page_id = NEW.page_id
 )
BEGIN
    SELECT RAISE(ABORT, 'activity_form_page_mismatch');
END;

CREATE TRIGGER IF NOT EXISTS trg_activity_validate_form_page_update
BEFORE UPDATE OF form_id, page_id ON activity_events
WHEN NEW.form_id IS NOT NULL
 AND NEW.page_id IS NOT NULL
 AND NOT EXISTS (
    SELECT 1
    FROM form_page_registry p
    WHERE p.form_id = NEW.form_id
      AND p.page_id = NEW.page_id
 )
BEGIN
    SELECT RAISE(ABORT, 'activity_form_page_mismatch');
END;


-- ============================================================
-- 7. REFERENCE INTEGRITY TRIGGERS
-- The stored page version must match the registered page version
-- when a reference is first issued.
-- ============================================================

CREATE TRIGGER IF NOT EXISTS trg_page_instance_validate_insert
BEFORE INSERT ON application_page_instances
WHEN NOT EXISTS (
    SELECT 1
    FROM form_page_registry p
    JOIN form_registry f ON f.form_id = p.form_id
    WHERE p.form_id = NEW.form_id
      AND p.page_id = NEW.page_id
      AND p.page_version = NEW.page_version
      AND p.page_status = 'active'
      AND f.form_status = 'active'
)
BEGIN
    SELECT RAISE(ABORT, 'page_reference_target_inactive_or_mismatched');
END;

CREATE TRIGGER IF NOT EXISTS trg_page_instance_validate_update
BEFORE UPDATE OF form_id, page_id, page_version
ON application_page_instances
WHEN NOT EXISTS (
    SELECT 1
    FROM form_page_registry p
    JOIN form_registry f ON f.form_id = p.form_id
    WHERE p.form_id = NEW.form_id
      AND p.page_id = NEW.page_id
      AND p.page_version = NEW.page_version
      AND p.page_status = 'active'
      AND f.form_status = 'active'
)
BEGIN
    SELECT RAISE(ABORT, 'page_reference_target_inactive_or_mismatched');
END;
